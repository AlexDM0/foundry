/**
 * The generated Info.plist and launch script pinned whole from the real templates, so a template change changes its pin in the same change. Every
 * value lands escaped for its file, so no path breaks out of its shell word or XML string, and a placeholder with no value fills nothing.
 */
import { readFileSync }           from 'node:fs';
import { join }                   from 'node:path';
import { describe, expect, test } from 'bun:test';

import { repositoryRoot }                        from '../../../testing/BoundaryRecordings.ts';
import { BundleTemplateUtil, type BundleValues } from './BundleTemplateUtil.ts';

const EXAMPLE_VALUES: BundleValues = {
  repositoryPath:       '/Users/example/Development/gaia',
  bunProgram:           '/Users/example/.bun/bin/bun',
  gaiaVersion:          '0.1.0',
  installVersion:       1,
  minimumSystemVersion: '12.0',
};

function templateText(fileName: string): string {
  return readFileSync(join(repositoryRoot(), 'resources', 'app-bundle', fileName), 'utf8');
}

const PINNED_INFO_PLIST = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key>
  <string>en</string>
  <key>CFBundleDisplayName</key>
  <string>Gaia</string>
  <key>CFBundleExecutable</key>
  <string>launch</string>
  <key>CFBundleIconFile</key>
  <string>Gaia</string>
  <key>CFBundleIdentifier</key>
  <string>local.gaia.app</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>CFBundleName</key>
  <string>Gaia</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>0.1.0</string>
  <key>CFBundleVersion</key>
  <string>0.1.0</string>
  <key>LSMinimumSystemVersion</key>
  <string>12.0</string>
  <key>LSUIElement</key>
  <true/>
  <key>NSAppSleepDisabled</key>
  <true/>
  <key>NSHighResolutionCapable</key>
  <true/>
  <key>GaiaInstallVersion</key>
  <integer>1</integer>
</dict>
</plist>
`;

const PINNED_LAUNCH_SCRIPT = `#!/bin/sh
# Gaia.app's launch script, generated by gaia install-app; installing the app again writes it anew.
# A Finder launch gives a bare PATH, so Bun is looked for at its usual places, and its folder leads the PATH of everything Gaia starts.

REPOSITORY_PATH='/Users/example/Development/gaia'
INSTALLING_BUN_PROGRAM='/Users/example/.bun/bin/bun'
BUNDLE_PATH="$(cd "$(dirname "$0")/../.." && pwd -P)"

show_failure() {
  /usr/bin/osascript -e 'on run argv' -e 'display alert (item 1 of argv) message (item 2 of argv) as critical' -e 'end run' 'Gaia' "$1" >/dev/null 2>&1
}

BUN_PROGRAM=''
for candidate_program in "$INSTALLING_BUN_PROGRAM" "$HOME/.bun/bin/bun" /opt/homebrew/bin/bun /usr/local/bin/bun; do
  if [ -x "$candidate_program" ]; then
    BUN_PROGRAM="$candidate_program"
    break
  fi
done
if [ -z "$BUN_PROGRAM" ]; then
  show_failure 'Gaia runs on Bun, and Bun is in none of the places Gaia looks for it.'
  exit 1
fi
if [ ! -f "$REPOSITORY_PATH/src/Main.ts" ]; then
  show_failure "Gaia's repository is no longer at $REPOSITORY_PATH."
  exit 1
fi

PATH="$(dirname "$BUN_PROGRAM"):$PATH"
export PATH
cd "$REPOSITORY_PATH" || exit 1
exec "$BUN_PROGRAM" run "$REPOSITORY_PATH/src/Main.ts" launch --app-bundle "$BUNDLE_PATH"
`;

describe('the generated Info.plist', () => {
  test('is pinned whole, with the install version, the version of Gaia and the keys of a background app that stays awake', () => {
    expect(BundleTemplateUtil.infoPlistOf(templateText('Info.plist.template'), EXAMPLE_VALUES)).toEqual({ verdict: 'filled', text: PINNED_INFO_PLIST });
  });

  test('escapes a version for XML', () => {
    const filled = BundleTemplateUtil.infoPlistOf(templateText('Info.plist.template'), { ...EXAMPLE_VALUES, gaiaVersion: '1.0.0-<example>&"beta"' });
    expect(filled.verdict === 'filled' ? filled.text : '').toContain('<string>1.0.0-&lt;example&gt;&amp;&quot;beta&quot;</string>');
  });
});

describe('the generated launch script', () => {
  test('is pinned whole: it finds Bun, shows a failure as a dialog, and runs the launch with its bundle named', () => {
    expect(BundleTemplateUtil.launchScriptOf(templateText('launch.sh.template'), EXAMPLE_VALUES)).toEqual({ verdict: 'filled', text: PINNED_LAUNCH_SCRIPT });
  });

  test('holds a repository path with spaces, quotes and a dollar sign as one shell word the shell reads back verbatim', () => {
    const filled = BundleTemplateUtil.launchScriptOf(templateText('launch.sh.template'), { ...EXAMPLE_VALUES, repositoryPath: '/Users/example/Alex\'s "work" $HOME' });
    expect(filled.verdict === 'filled' ? filled.text : '').toContain('REPOSITORY_PATH=\'/Users/example/Alex\'\\\'\'s "work" $HOME\'\n');
  });
});

describe('a template', () => {
  test('with a placeholder that has no value is not filled, and names every such placeholder once', () => {
    expect(BundleTemplateUtil.filledTemplateOf('{{KNOWN}} {{UNKNOWN}} {{UNKNOWN}} {{OTHER}}', { KNOWN: 'value' }))
      .toEqual({ verdict: 'unfilled', placeholders: ['UNKNOWN', 'OTHER'] });
  });

  test('takes a value with replacement patterns in it literally', () => {
    expect(BundleTemplateUtil.filledTemplateOf('a {{NAME}} b', { NAME: '$& $1 $$' })).toEqual({ verdict: 'filled', text: 'a $& $1 $$ b' });
  });
});
